"""Build the single-file Bash CLI and check that the published copy is current."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START = "# BEGIN ARCHIVE HELPER\n"
END = "# END ARCHIVE HELPER\n"
DELIMITER = "WP_MIGRATE_PYTHON"

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
options = parser.parse_args()
script = (ROOT / "wp-migrate").read_text(encoding="utf-8")
helper = (ROOT / "lib/backup.py").read_text(encoding="utf-8")
before, remainder = script.split(START)
_, after = remainder.split(END)
if DELIMITER in helper.splitlines():
    parser.error("Archive helper contains the Bash heredoc delimiter")
embedded = f"backup_helper() {{\n  python3 - \"$@\" <<'{DELIMITER}'\n{helper.rstrip()}\n{DELIMITER}\n}}\n"
bundle = before.replace(
    "#!/usr/bin/env bash\n",
    "#!/usr/bin/env bash\n# Generated by tools/build-standalone.py.\n",
    1,
) + embedded + after
destination = ROOT / "dist/wp-migrate"
if options.check:
    if not destination.is_file() or destination.read_bytes() != bundle.encode("utf-8"):
        parser.error("Standalone CLI is stale. Run tools/build-standalone.py.")
else:
    destination.parent.mkdir(exist_ok=True)
    destination.write_bytes(bundle.encode("utf-8"))
